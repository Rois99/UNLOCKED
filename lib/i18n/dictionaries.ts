export const dictionaries: Record<Locale, Dictionary> = { en, he };

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (LOCALES as readonly string[]).includes(value);
}

/** Hebrew name when the user reads Hebrew and one exists; otherwise the English name. */
export function localName(row: { name: string; name_he?: string | null } | null | undefined, locale: Locale): string {
  if (!row) return '';
  return locale === 'he' && row.name_he ? row.name_he : row.name;
}

